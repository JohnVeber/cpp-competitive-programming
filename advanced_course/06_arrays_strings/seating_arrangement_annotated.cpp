// ============================================================
// Задача: Рассадка участников
// Источник: Модуль 1, Тема 1.6 - Массивы и строки
// ============================================================

#include <iostream>
#include <vector>
using namespace std;
// ------------------------------------------------------------
// Подход
// ------------------------------------------------------------
// Пусть K - максимальное количество участников из одной школы.
// Чтобы никакие два участника из этой школы не сидели рядом,
// между ними нужен хотя бы один «разделитель» из другой школы.
// Для K участников нужно минимум K - 1 разделителей.
// Остальных участников N - K, поэтому необходимо:
//     N - K >= K - 1   =>   K <= (N + 1) / 2
//
// Это условие является и достаточным: если оно выполнено, можно
// поставить участников самой популярной школы на позиции 0, 2, 4, …,
// а остальных - на позиции 1, 3, 5, …. Тогда никакие два
// одинаковых значения не окажутся рядом.
//
// Алгоритм:
//   1. Получить N - количество учеников.
//   2. Объявить массив (или вектор) из N элементов - номеров школ.
//   3. Заполнить его значениями с клавиатуры.
//   4. Для каждой школы подсчитать, сколько раз она встречается
//      в массиве, и найти максимум среди этих счётчиков (maxCount).
//   5. Сравнить maxCount с (N + 1) / 2: если maxCount не больше,
//      рассадка возможна (YES), иначе невозможна (NO).
//
// Граничные случаи:
//   - N = 1: всегда YES (нет пары, которая может конфликтовать).
//   - Все участники из одной школы и N > 1: NO.
//   - Чётное / нечётное N: формула (N + 1) / 2 учитывает оба случая.
//
// Сложность:
//   Время:  O(N + MAX_SCHOOL) - чтение N чисел и проход по счётчикам.
//   Память: O(N + MAX_SCHOOL) - массив школ и вектор счётчиков.
// ------------------------------------------------------------

int main() {
    // --------------------------------------------------------
    // Ограничения на вводимые величины
    // --------------------------------------------------------
    // Чтобы решение работало корректно и не выходило за границы
    // векторов, при вводе с клавиатуры должны выполняться условия:
    //
    //   1. N - целое число, 1 <= N <= 10^6.
    //      При N = 0 задача не имеет смысла (нет участников),
    //      при N < 0 вектор schools(N) создать нельзя.
    //      Верхняя граница 10^6 выбрана как типичный максимум
    //      для олимпиадных задач; при большем N решение может
    //      не уложиться в лимит времени из-за чтения данных.
    //
    //   2. Каждый номер школы - целое число в диапазоне
    //      1 <= school <= MAX_SCHOOL, где MAX_SCHOOL = 100000.
    //      Школы нумеруются с 1 (школы №0 не существует),
    //      поэтому элемент count[0] не используется.
    //      Если номер школы больше MAX_SCHOOL, произойдёт
    //      выход за границы вектора count - неопределённое
    //      поведение.
    //      В этом случае нужно увеличить MAX_SCHOOL
    //      и перекомпилировать решение.
    //
    //   3. Количество введённых номеров школ должно быть
    //      ровно N. Если ввести меньше - программа будет
    //      ждать ввода; если больше - лишние числа останутся
    //      в буфере ввода и не повлияют на результат, но
    //      это нарушает формат задачи.
    //
    //   4. Все номера школ должны быть целыми числами.
    //      Ввод нецелого значения (например, 2.5) приведёт
    //      к ошибке чтения: cin перейдёт в состояние fail,
    //      и дальнейшее чтение будет некорректным.
    //
    // Эти ограничения - не «пожелания», а условия корректности.
    // При их нарушении решение может дать неверный ответ
    // или аварийно завершиться.
    // --------------------------------------------------------

    int N; // Количество участников
    cin >> N;

    // MAX_SCHOOL - максимальный номер школы, который может встретиться во входных данных.
    // Если номер школы больше MAX_SCHOOL, решение не сработает: произойдёт выход за границы вектора count.
    const int MAX_SCHOOL = 100000;

    // schools - вектор из номеров школ участников; размер N считывается из входных данных, и поэтому
    // размер вектора известен до его создания. Однако вместо массива фиксированного размера вектор выбран,
    // поскольку размер зависит от входных данных и не может быть задан константой на этапе компиляции.
    vector<int> schools(N); // Количество номеров школ равно количеству участников.

    // 1. Заполняем вектор: читаем N номеров школ.
    for (int i = 0; i < N; ++i) {
        cin >> schools[i];
    }

    // count - вектор счётчиков вида: count[номер_школы] - количество участников из этой школы.
    // Школы нумеруются с 1 (школы №0 не существует), поэтому элемент count[0] не используется и всегда остаётся нулём.
    // Размер вектора MAX_SCHOOL + 1: индексы идут от 0 до MAX_SCHOOL включительно, всего MAX_SCHOOL + 1 элементов.
    // Второй аргумент инициализирует вектор нулями.
    vector<int> count(MAX_SCHOOL + 1, 0);

    int maxCount = 0; // maxCount - максимальное количество участников из одной школы.

    // 2. Подсчитываем, сколько раз каждая школа встречается в векторе schools, и находим максимум среди счётчиков.
    for (int i = 0; i < N; ++i) {
        int school = schools[i];

        // ++count[school] - увеличивает счётчик школы school на 1.
        ++count[school];

        // Если счётчик этой школы стал больше текущего максимума, значит, это новый максимум - обновляем maxCount.
        // Обновление на лету избавляет от повторного прохода по всему вектору count после цикла.
        if (count[school] > maxCount) {
            maxCount = count[school];
        }
    }

    // 3. Проверяем критерий: maxCount <= (N + 1) / 2.
    // Если да - рассадка возможна, иначе - нет.
    if (maxCount <= (N + 1) / 2) {
        cout << "Для " << N << " учеников и " << N << " номеров школ задача выполнима: YES\n";
    } else {
        cout << "Для " << N << " учеников и " << N << " номеров школ задача не выполнима: NO\n";
    }

    return 0;
}