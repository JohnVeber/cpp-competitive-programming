#include <iostream>
using namespace std;

// ------------------------------------------------------------
// Подход
// ------------------------------------------------------------
// Задача рекурсивна по своей природе. Чтобы перенести N дисков
// с первого стержня на третий, достаточно:
//   1. Перенести верхние N - 1 дисков на вспомогательный стержень.
//   2. Переложить самый большой диск на целевой стержень (1 ход).
//   3. Перенести те же N - 1 дисков с вспомогательного стержня
//      на целевой.
//
// Складывая ходы всех трёх шагов, получаем рекуррентное
// соотношение:
//     hanoi(N) = hanoi(N - 1) + 1 + hanoi(N - 1)
// что после приведения подобных слагаемых даёт:
//     hanoi(N) = 2 * hanoi(N - 1) + 1
// В этом выражении hanoi(N) - функция, которая возвращает минимальное
// число ходов для N дисков.
//
// База рекурсии - это значение, при котором рекурсия
// останавливается и дальше не углубляется. Без базы рекурсия
// была бы бесконечной. Для этой задачи база: hanoi(1) = 1
// (один диск переносится за один ход). Можно также взять
// hanoi(0) = 0 - тогда формула работает и для N = 1:
// 2 * hanoi(0) + 1 = 1.
//
// Попробуем получить замкнутую формулу - это выражение hanoi(N) через
// N без рекурсии. Для этого развернём рекуррентное соотношение:
//
//   hanoi(N) = 2 * hanoi(N-1) + 1
//            = 2 * (2 * hanoi(N-2) + 1) + 1
//            = 4 * hanoi(N-2) + 2 + 1
//            = 4 * (2 * hanoi(N-3) + 1) + 2 + 1
//            = 8 * hanoi(N-3) + 4 + 2 + 1
//            ...
//            = 2^k * hanoi(N-k) + (2^k - 1)
//
// При k = N остаётся hanoi(0) = 0, поэтому:
//   hanoi(N) = 2^N - 1
//
// Проверка: hanoi(1) = 1, hanoi(2) = 3, hanoi(3) = 7 - совпадает
// с примером из условия. В коде требуется рекурсивная функция,
// поэтому замкнутая формула здесь не используется. Она приведена
// для двух целей: (1) «ручной» проверки решения на маленьких N -
// можно подставить N и сравнить с ответом программы; (2) оценки
// сложности - из неё видно, что число ходов растёт как 2^N, то есть
// экспоненциально, и при больших N решение по времени неприемлемо.
//
// Алгоритм:
//   1. Получить N - количество дисков.
//   2. Вызвать функцию hanoi(N), которая возвращает минимальное
//      число ходов.
//   3. Вывести результат.
//
// Граничные случаи:
//   - N = 1: hanoi(1) = 1.
//   - N = 30: hanoi(30) = 2^30 - 1 = 1 073 741 823, что меньше
//     INT_MAX (2 147 483 647), поэтому тип int достаточен.
//   - Переполнение происходит только при N = 32, а т.к. в условии
//     N <= 30 - выход за пределы диапазона значений int невозможен.
//
// Сложность:
//   Время:  O(2^N) - рекурсивных вызовов ровно 2^N - 1.
//   Память: O(N)   - глубина стека рекурсии равна N.
// ------------------------------------------------------------

// hanoi(n) - возвращает минимальное число ходов для переноса n
// дисков с одного стержня на другой по правилам задачи.
int hanoi(int n) {
    // База рекурсии: один диск переносится за один ход.
    // Без этой проверки функция вызывала бы себя бесконечно.
    if (n == 1) {
        return 1;
    }

    // Рекуррентное соотношение (см. описание подхода).
    return 2 * hanoi(n - 1) + 1;
}

int main() {
    // --------------------------------------------------------
    // Ограничения на вводимые величины
    // --------------------------------------------------------
    // Чтобы решение работало корректно, при вводе с клавиатуры
    // должны выполняться условия:
    //
    //   1. N - целое число, 1 <= N <= 30.
    //      При N = 0 задача не имеет смысла (нет дисков),
    //      при N < 0 рекурсия не дойдёт до базы.
    //      Верхняя граница 30 выбрана из условия задачи:
    //      при N = 30 результат 2^30 - 1 = 1 073 741 823
    //      ещё помещается в int, при N = 32 было бы переполнение.
    //
    //   2. N должно быть целым числом. Ввод нецелого значения
    //      (например, 2.5) приведёт к ошибке чтения: cin
    //      перейдёт в состояние fail, и дальнейшее чтение
    //      будет некорректным.
    //
    // Эти ограничения - не «пожелания», а условия корректности.
    // При их нарушении решение может дать неверный ответ
    // или аварийно завершиться.
    // --------------------------------------------------------

    int N; // Количество дисков
    cin >> N;

    // Вызываем функцию hanoi и выводим результат.
    cout << hanoi(N) << "\n";

    return 0;
}