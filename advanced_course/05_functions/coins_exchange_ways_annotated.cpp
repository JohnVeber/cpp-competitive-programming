// ============================================================
// Задача: Количество разменов
// Источник: Модуль 1, Тема 1.5 - Декомпозиция программ с помощью функций
// ============================================================

#include <iostream>
using namespace std;

// ------------------------------------------------------------
// Подход
// ------------------------------------------------------------
// Задача сводится к подсчёту количества комбинаций (порядок
// монет не важен: 1+2 и 2+1 - один и тот же размен).
//
// Идея рекурсии: чтобы разменять сумму S, начиная с монеты
// с индексом idx, можно либо:
//   - взять ещё одну монету с индексом idx и разменять
//     оставшуюся сумму S - coins[idx] теми же монетами;
//   - перейти к следующей монете (idx + 1) и разменять S
//     оставшимися монетами (с индексами idx+1 и далее,
//     вплоть до последней).
//
// Фиксация порядка монет (сначала все монеты a, потом b, потом c)
// гарантирует, что каждая комбинация учитывается ровно один раз,
// а не как перестановка.
//
// База рекурсии - это условие, при котором рекурсивная функция
// прекращает вызывать саму себя и возвращает готовый ответ.
// Без базы рекурсия была бы бесконечной. В этой задаче две базы:
//   - S == 0: сумма разменяна, это один способ (ничего не берём);
//   - S < 0 или idx == 3: разменять нельзя, способов ноль.
//
// Алгоритм:
//   1. Получить a, b, c, S.
//   2. Вызвать функцию count_ways(a, b, c, S).
//   3. Вывести результат.
//
// Граничные случаи:
//   - S = 0: ответ 1 (пустой размен).
//   - Монета больше S: она не участвует, рекурсия её пропускает.
//   - Одинаковые номиналы: комбинации не дублируются, потому что
//     порядок монет фиксирован.
//
// Сложность:
//   Время:  экспоненциальная (без мемоизации), зависит от S и
//           номиналов. Для учебных ограничений (небольшое S)
//           этого достаточно.
//   Память: O(S) - глубина стека рекурсии.
//
// Тип результата: количество способов может быть большим,
// однако согласно условию задачи возвращаемый тип - int, а не long long например.
// ------------------------------------------------------------

// count_ways_rec(coins, idx, S) - вспомогательная рекурсивная функция.
// coins - массив из трёх номиналов.
// idx - индекс текущей монеты (0, 1 или 2)
// S - оставшаяся сумма на данном шаге рекурсии.
int count_ways_rec(int coins[3], int idx, int S) {
    // Объявляем переменные для результатов двух вариантов.

    // take — количество способов размена, если текущую монету
    // coins[idx] мы берём хотя бы один раз (и продолжаем
    // разменивать оставшуюся сумму той же монетой).
    int take = 0;

    // skip — количество способов размена, если текущую монету
    // coins[idx] мы больше не берём и переходим к следующей.
    int skip = 0;

    // --------------------------------------------------------
    // База рекурсии 1: сумма разменяна.
    // S == 0 означает, что мы набрали ровно нужную сумму.
    // Это один способ - ничего больше не добавлять.
    // --------------------------------------------------------
    if (S == 0) {
        return 1;
    }

    // --------------------------------------------------------
    // База рекурсии 2: разменять нельзя.
    // S < 0 - мы перебрали сумму (взяли слишком много монет).
    // idx == 3 - монеты закончились, а сумма ещё не набрана.
    // В обоих случаях способов ноль.
    // --------------------------------------------------------
    if (S < 0 || idx == 3) {
        return 0;
    }

    // --------------------------------------------------------
    // Вариант 1: взять ещё одну монету coins[idx].
    // Сумма уменьшается на coins[idx], индекс монеты не меняется
    // (ту же монету можно брать сколько угодно раз).
    // --------------------------------------------------------
    take = count_ways_rec(coins, idx, S - coins[idx]);

    // --------------------------------------------------------
    // Вариант 2: не брать монету coins[idx], перейти к следующей.
    // Сумма не меняется, индекс увеличивается на 1.
    // --------------------------------------------------------
    skip = count_ways_rec(coins, idx + 1, S);

    // --------------------------------------------------------
    // Общее количество способов - сумма обоих вариантов.
    // --------------------------------------------------------
    return take + skip;
}

// count_ways(a, b, c, S) - основная функция.
// Возвращает количество способов, которыми можно
// разменять сумму S монетами номиналов a, b, c (каждая монета
// может использоваться неограниченное количество раз).
int count_ways(int a, int b, int c, int S) {
    // Массив номиналов: coins[0] = a, coins[1] = b, coins[2] = c.
    int coins[3] = {a, b, c};

    // Запускаем рекурсию с первой монеты (idx = 0) и полной суммой S.
    return count_ways_rec(coins, 0, S);
}

int main() {
    // --------------------------------------------------------
    // Ограничения на вводимые величины
    // --------------------------------------------------------
    // Чтобы решение работало корректно, при вводе с клавиатуры
    // должны выполняться условия:
    //
    //   1. a, b, c - целые положительные числа (номиналы монет).
    //      Нулевой или отрицательный номинал не имеет смысла.
    //
    //   2. S - целое неотрицательное число (сумма для размена).
    //      При S = 0 ответ 1 (пустой размен).
    //
    //   3. S не должно быть слишком большим: без мемоизации
    //      рекурсия может работать долго при больших S.
    //      Для учебных ограничений (небольшое S) этого достаточно.
    //
    // Эти ограничения - не «пожелания», а условия корректности.
    // При их нарушении решение может дать неверный ответ
    // или аварийно завершиться.
    // --------------------------------------------------------

    int a, b, c, S;
    cin >> a >> b >> c >> S;

    // Вызываем функцию count_ways и выводим результат.
    cout << count_ways(a, b, c, S) << "\n";

    return 0;
}